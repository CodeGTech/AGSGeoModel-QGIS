"""Issues tab: AGS validation, geological consistency and modelling findings with candidate
explanations. Reviewer status (open / accepted / dismissed) is stored in ``issues.status`` and carried
over when the findings are regenerated by the next run."""

from __future__ import annotations

import json

from qgis.PyQt.QtCore import Qt, pyqtSignal
from qgis.PyQt.QtGui import QColor
from qgis.PyQt.QtWidgets import (
    QAbstractItemView,
    QComboBox,
    QHBoxLayout,
    QHeaderView,
    QLabel,
    QPushButton,
    QTableWidget,
    QTableWidgetItem,
    QTextBrowser,
    QVBoxLayout,
    QWidget,
)

from .. import workflows as wf
from ..database import GeoPackage

SEVERITY_ORDER = {"critical": 0, "error": 1, "warning": 2, "info": 3}
SEVERITY_HEX = {"critical": "#7B1FA2", "error": "#C62828", "warning": "#F57F17", "info": "#607D8B"}
COLUMNS = ["Severity", "Rule", "Category", "Holes", "Depth", "Message", "Status"]


class IssuesPanel(QWidget):
    zoomTo = pyqtSignal(str)

    def __init__(self, parent=None):
        super().__init__(parent)
        self.folder: str | None = None
        self.rows: list[dict] = []
        lay = QVBoxLayout(self)
        f = QHBoxLayout()
        self.severity = QComboBox()
        self.severity.addItems(["all severities", "critical", "error", "warning", "info"])
        self.category = QComboBox()
        self.category.addItems(["all categories", "ags", "engineering", "geology", "model", "bgs"])
        self.status = QComboBox()
        self.status.addItems(["open", "all statuses", "accepted", "dismissed"])
        for w in (self.severity, self.category, self.status):
            w.currentIndexChanged.connect(self._fill)
            f.addWidget(w)
        f.addStretch(1)
        lay.addLayout(f)
        self.summary = QLabel("")
        lay.addWidget(self.summary)
        self.table = QTableWidget(0, len(COLUMNS))
        self.table.setHorizontalHeaderLabels(COLUMNS)
        self.table.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
        self.table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
        self.table.horizontalHeader().setSectionResizeMode(QHeaderView.ResizeMode.ResizeToContents)
        self.table.horizontalHeader().setStretchLastSection(True)
        self.table.itemSelectionChanged.connect(self._details)
        self.table.cellDoubleClicked.connect(lambda r, c: self._zoom())
        lay.addWidget(self.table, 2)
        self.detail = QTextBrowser()
        self.detail.setOpenExternalLinks(True)
        lay.addWidget(self.detail, 1)
        b = QHBoxLayout()
        for label, st in (("Accept", "accepted"), ("Dismiss", "dismissed"), ("Re-open", "open")):
            btn = QPushButton(label)
            btn.clicked.connect(lambda _=False, s=st: self._set_status(s))
            b.addWidget(btn)
        z = QPushButton("Zoom to hole")
        z.clicked.connect(self._zoom)
        b.addWidget(z)
        b.addStretch(1)
        lay.addLayout(b)

    def set_project(self, folder: str | None) -> None:
        self.folder = folder
        self.refresh()

    def refresh(self) -> None:
        self.rows = []
        if self.folder and wf.gpkg_path(self.folder).exists():
            gp = GeoPackage(wf.gpkg_path(self.folder), create=False)
            try:
                self.rows = gp.read("issues")
            finally:
                gp.close()
        self.rows.sort(key=lambda r: (SEVERITY_ORDER.get(r["severity"], 9), r["rule"] or "", r["location_ids"] or ""))
        self._fill()

    def _visible(self) -> list[dict]:
        sev, cat, st = self.severity.currentText(), self.category.currentText(), self.status.currentText()
        return [
            r
            for r in self.rows
            if (sev.startswith("all") or r["severity"] == sev)
            and (cat.startswith("all") or r["category"] == cat)
            and (st.startswith("all") or (r["status"] or "open") == st)
        ]

    def _fill(self) -> None:
        rows = self._visible()
        counts = {}
        for r in self.rows:
            if (r["status"] or "open") == "open":
                counts[r["severity"]] = counts.get(r["severity"], 0) + 1
        self.summary.setText(
            "Open: " + ", ".join(f"{counts.get(s, 0)} {s}" for s in SEVERITY_ORDER)
            if self.rows
            else "No findings stored yet."
        )
        self.table.setRowCount(len(rows))
        for i, r in enumerate(rows):
            vals = [
                r["severity"],
                r["rule"],
                r["category"],
                r["location_ids"] or "",
                "" if r["depth"] is None else f"{r['depth']:.2f}",
                r["message"],
                r["status"] or "open",
            ]
            for c, v in enumerate(vals):
                it = QTableWidgetItem(str(v))
                if c == 0:
                    it.setForeground(QColor(SEVERITY_HEX.get(r["severity"], "#000000")))
                it.setData(Qt.ItemDataRole.UserRole, r["fid"])
                self.table.setItem(i, c, it)

    def _current(self) -> list[dict]:
        fids = {self.table.item(i.row(), 0).data(Qt.ItemDataRole.UserRole) for i in self.table.selectedIndexes()}
        return [r for r in self.rows if r["fid"] in fids]

    def _details(self) -> None:
        cur = self._current()
        if not cur:
            self.detail.clear()
            return
        r = cur[0]
        expl = r["explanations"]
        if isinstance(expl, str):
            try:
                expl = json.loads(expl)
            except json.JSONDecodeError:
                expl = [expl]
        html = [f"<b>{r['rule']}</b> ({r['severity']}, {r['category']})<br>{r['message']}"]
        if expl:
            html.append(
                "<br><b>Possible geological explanations</b><ul>" + "".join(f"<li>{e}</li>" for e in expl) + "</ul>"
            )
        if r["suggestion"]:
            html.append(f"<b>Suggested action:</b> {r['suggestion']}")
        self.detail.setHtml("".join(html))

    def _set_status(self, status: str) -> None:
        cur = self._current()
        if not cur or not self.folder:
            return
        gp = GeoPackage(wf.gpkg_path(self.folder), create=False)
        try:
            gp.conn.executemany("UPDATE issues SET status = ? WHERE fid = ?", [(status, r["fid"]) for r in cur])
            gp.conn.commit()
        finally:
            gp.close()
        self.refresh()

    def _zoom(self) -> None:
        cur = self._current()
        if cur and cur[0]["location_ids"]:
            self.zoomTo.emit(cur[0]["location_ids"].split(",")[0])
